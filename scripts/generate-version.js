// Stamps the running build with the real git commit + build time, so the
// version shown in the app can never drift from what was actually deployed
// (previously a human had to remember to bump src/app/constants/version.ts
// by hand on every release, which is exactly what went wrong once already).
// Runs automatically before `npm run build` via the "prebuild" npm script.
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

function run(cmd, fallback) {
  try {
    return execSync(cmd, { encoding: 'utf8' }).trim();
  } catch {
    return fallback;
  }
}

const hash = run('git rev-parse --short HEAD', 'unknown');
const dirty = run('git status --porcelain', '').length > 0 ? '-dirty' : '';
const version = `${hash}${dirty}`;
const builtAt = new Date().toISOString();

const versionTsPath = path.join(__dirname, '..', 'src', 'app', 'constants', 'version.ts');
const versionJsonPath = path.join(__dirname, '..', 'src', 'assets', 'version.json');

fs.writeFileSync(versionTsPath, `// Auto-generated by scripts/generate-version.js on every build — do not edit by hand.
export const APP_VERSION = {
  version: '${version}',
  description: 'Built ${builtAt}'
};
`);

fs.mkdirSync(path.dirname(versionJsonPath), { recursive: true });
fs.writeFileSync(versionJsonPath, JSON.stringify({ version, builtAt }, null, 2));

console.log(`Stamped build version: ${version} (${builtAt})`);
